def _instantiate(cls):
    """Instancia um ValidationError com dados de exemplo, se possivel."""
    hints = typing.get_type_hints(cls)
    kwargs = {}
    for f in dataclasses.fields(cls):
        if f.name in ("location", "severity"):
            continue
        if f.default is not dataclasses.MISSING or f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
            continue
        kwargs[f.name] = _sample(f.name, hints.get(f.name))
    try:
        return cls(location=None, **kwargs)
    except Exception:
        try:
            return cls(**kwargs)
        except Exception:
            return None


def _cli_line(inst) -> str:
    """One-line English message of the diagnostic, used as its summary."""
    if inst is None:
        return ""
    try:
        line = _neutral(inst.to_cli_line()).strip()
        block = getattr(inst, "block", None)
        if isinstance(block, str):
            for prefix in (f"{block}: ", f"`{block}`: "):
                if line.startswith(prefix):
                    line = line[len(prefix):]
                    line = line[:1].upper() + line[1:]
        return line
    except Exception as exc:  # noqa: BLE001
        UNRENDERABLE.append((getattr(inst, "CODE", "?"), type(inst).__name__, f"{type(exc).__name__}: {exc}"))
        return ""


def _quoted(text: str) -> str:
    """Frontmatter value in double quotes, with inner quotes escaped."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen_diagnostics(lang: str = "en") -> dict[str, str]:
    t = L[lang]
    out: dict[str, str] = {}

    classes = [
        (o.CODE, n, o)
        for n, o in vars(R).items()
        if inspect.isclass(o)
        and dataclasses.is_dataclass(o)
        and isinstance(getattr(o, "CODE", None), str)
    ]
    # CODE nao e unico: E064 e compartilhado por 3 classes. Agrupa por CODE.
    by_code: dict[str, list] = {}
    for code, name, cls in classes:
        by_code.setdefault(code, []).append((name, cls))

    for code, members in sorted(by_code.items()):
        first_cls = members[0][1]
        sev_key = "severity_" + getattr(first_cls, "DEFAULT_SEVERITY", R.ErrorSeverity.ERROR).value
        local_export = issubclass(first_cls, R.ExportBlockError)
        insts = [(n, c, _instantiate(c)) for n, c in members]
        lines = [(n, _cli_line(i)) for n, _c, i in insts]
        summary = (lines[0][1] or code).rstrip(".")

        parts = [
            frontmatter(
                id=code,
                title=f'"{code}"',
                category="diagnostic",
                summary=_quoted(summary + "."),
                severity=t[sev_key],
                see_also=[],
                source="generated",
                requires_synesis=f'">={SYNESIS_VERSION}"',
            ),
            "",
            t["gen_warning"],
            "",
            f"# {code} — {t[sev_key]}",
            "",
            f"## {t['sec_desc']}",
            "",
        ]

        if len(members) == 1:
            parts.append((lines[0][1] or code) + ".")
        else:
            parts.append(t["covers"].format(n=len(members)))
            parts.append("")
            for n, d in lines:
                parts.append(f"- **{n}** — {d or n}")
        severity_text = t["severity_text_" + sev_key.split("_")[1]]
        if local_export:
            severity_text = t["severity_text_export"]
        parts += ["", f"## {t['sec_severity']}", "", severity_text]

        parts += ["", f"## {t['sec_message']}", ""]
        for n, cls, inst in insts:
            msg = None
            if inst is not None:
                try:
                    msg = inst.to_diagnostic()
                except Exception as exc:  # noqa: BLE001
                    # Falha ao renderizar e sinal de defeito no compilador,
                    # nao motivo para omitir a entry em silencio.
                    UNRENDERABLE.append((code, n, f"{type(exc).__name__}: {exc}"))
            if len(members) > 1:
                parts.append(f"**{n}**")
                parts.append("")
            if msg is None:
                parts += [t["not_reproducible"], ""]
            else:
                parts += ["```text", msg.strip(), "```", ""]

        parts += [f"## {t['sec_context']}", "", t["fields_intro"], ""]
        for n, cls in members:
            fields = [
                f.name
                for f in dataclasses.fields(cls)
                if f.name not in ("location", "severity")
            ]
            detail = ", ".join(f"`{x}`" for x in fields) or "—"
            parts.append(f"- **{n}**: {detail}")
        parts.append("")

        out[code] = "\n".join(parts)
    return out


