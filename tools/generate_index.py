"""Write the master index of the guide: the "menu", in the Norton Guides spirit.

Uma linha por verbete: identificador, titulo e a frase de resumo. E a tela de
entrada da navegacao, e o unico lugar onde o guia inteiro cabe de uma vez.

Uso:
    python tools/generate_index.py
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENTRIES = ROOT / "synesis_help" / "entries"
OUT = ROOT / "INDEX.md"

# Ordem de apresentacao: do panorama ao detalhe, erros por ultimo.
ORDER = [
    ("overview", "Overview", "Start here."),
    ("block", "Blocks", "The structures of the language."),
    ("field_type", "Field types", "What each TYPE accepts."),
    ("modifier", "Modifiers", "Field and project properties."),
    ("linkage", "Linkage", "IDENTIFIES and REFERS TO."),
    ("case_study", "Case studies", "Complete projects adapted from real research."),
    ("ecosystem", "Ecosystem", "The tools around the language."),
    ("diagnostic", "Diagnostics", "Every error, warning and notice of the compiler."),
]


def parse_frontmatter(text: str) -> dict[str, str]:
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    out: dict[str, str] = {}
    for line in text[3:end].splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            out[k.strip()] = v.strip().strip('"')
    return out


def main() -> int:
    by_cat: dict[str, list[dict[str, str]]] = defaultdict(list)
    for md in sorted(ENTRIES.rglob("*.md")):
        fm = parse_frontmatter(md.read_text(encoding="utf-8"))
        if fm.get("id"):
            by_cat[fm.get("category", "?")].append(fm)

    total = sum(len(v) for v in by_cat.values())
    lines = [
        "# Synesis Guide — Index",
        "",
        f"{total} entries. Quick reference to the Synesis language.",
        "",
        "> Generated by `tools/generate_index.py`. Do not edit by hand.",
        "",
    ]

    for cat, title, blurb in ORDER:
        items = by_cat.get(cat, [])
        if not items:
            continue
        lines += [f"## {title}", "", f"*{blurb}*", ""]
        if cat == "diagnostic":
            lines += ["| Code | Situation |", "|---|---|"]
            for fm in sorted(items, key=lambda x: x["id"]):
                sev = fm.get("severity", "")
                mark = {"Warning": " ⚠", "Information": " ℹ"}.get(sev, "")
                lines.append(f"| [`{fm['id']}`]({fm['id']}){mark} | {fm.get('summary','')} |")
        else:
            lines += ["| Entry | Description |", "|---|---|"]
            # Same didactic order as the TUI: `order` first, title on ties.
            key = lambda x: (int(x.get("order", 100)), x.get("title", ""))
            for fm in sorted(items, key=key):
                lines.append(
                    f"| [**{fm.get('title')}**]({fm['id']}) | {fm.get('summary','')} |"
                )
        lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Index written: {OUT} ({total} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
