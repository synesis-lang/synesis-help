def gen_linkage(lang: str = "en") -> dict[str, str]:
    t = L[lang]
    info = get_language_info()
    rows = ["| Scope | `IDENTIFIES` | `REFERS TO` |", "|---|---|---|"]
    codes: set[str] = set()
    for scope in info.scopes:
        props = {p.name: p for p in info.linkage_by_scope.get(scope, [])}
        cells = []
        for mod in ("IDENTIFIES", "REFERS TO"):
            p = props.get(mod)
            if p is None:
                cells.append("—")
            else:
                lab = t[REQ_LABEL[p.requirement]]
                if p.error_code:
                    codes.add(p.error_code)
                    lab += f" ({p.error_code})"
                cells.append(lab)
        rows.append(f"| `{scope}` | {cells[0]} | {cells[1]} |")

    see = sorted(codes)
    body = [
        frontmatter(
            id="LINKAGE_SCOPES",
            title='"Scopes and linking between projects"',
            category="linkage",
            summary='"Where IDENTIFIES and REFERS TO can be declared."',
            syntax="FIELD <name> TYPE <type> SCOPE SOURCE "
            "<IDENTIFIES|REFERS TO> <entity> END FIELD",
            see_also=see,
            source="generated",
            requires_synesis=f'">={SYNESIS_VERSION}"',
        ),
        "",
        t["gen_warning"],
        "",
        "# Scopes and linking",
        "",
        f"## {t['sec_desc']}",
        "",
        "The modifiers `IDENTIFIES` and `REFERS TO` link independent projects:",
        "one project declares who an entity is, another refers to it. Not every",
        "scope accepts them.",
        "",
        f"## {t['sec_syntax']}",
        "",
        "```synesis",
        "FIELD <name> TYPE <type>",
        "    SCOPE SOURCE",
        "    [IDENTIFIES <entity>]",
        "    [REFERS TO <entity>]",
        "END FIELD",
        "```",
        "",
        t["syntax_legend"],
        "",
        f"## {t['sec_rules']}",
        "",
        "\n".join(rows),
        "",
        f"## {t['sec_seealso']}",
        "",
        ", ".join(f"`{s}`" for s in see) or "—",
        "",
    ]
    return {"LINKAGE_SCOPES": "\n".join(body)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail on drift")
    args = ap.parse_args()

    entries: dict[str, str] = {}
    entries.update(gen_field_types())
    entries.update(gen_diagnostics())
    entries.update(gen_linkage())

    OUT.mkdir(parents=True, exist_ok=True)

    if args.check:
        drift = []
        for eid, content in entries.items():
            p = OUT / f"{eid}.md"
            if not p.exists() or p.read_text(encoding="utf-8") != content:
                drift.append(eid)
        # `ECO_*` sai de tools/generate_ecosystem.py, que grava no mesmo
        # diretorio. Sem esta excecao elas contam como orfas e o --check
        # NUNCA fica verde — um check sempre vermelho e um check ignorado,
        # e seria justamente o que esconderia uma orfa de verdade.
        existing = {
            p.stem for p in OUT.glob("*.md") if not p.stem.startswith("ECO_")
        }
        orphans = existing - set(entries)
        if drift or orphans:
            print(f"DRIFT: {len(drift)} outdated, {len(orphans)} orphan")
            for d in sorted(drift)[:10]:
                print(f"  ~ {d}")
            for o in sorted(orphans)[:10]:
                print(f"  - {o}")
            return 1
        print(f"OK: {len(entries)} entries in sync (synesis {SYNESIS_VERSION})")
        return 0

    for eid, content in entries.items():
        (OUT / f"{eid}.md").write_text(content, encoding="utf-8")
    print(f"Generated {len(entries)} entries in {OUT} (synesis {SYNESIS_VERSION})")

    if UNRENDERABLE:
        print(f"\nWARNING: {len(UNRENDERABLE)} diagnostic(s) did not render.")
        print("This is a finding about the compiler, not a failure of the guide:")
        for code, name, err in UNRENDERABLE:
            print(f"  {code} {name}: {err}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
