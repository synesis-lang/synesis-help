#: Placeholder the compiler uses in its own explanations (language_info).
_COMPILER_PLACEHOLDER = re.compile(r"nome_do_campo")


def _neutral(text: str) -> str:
    return _COMPILER_PLACEHOLDER.sub("field_name", text)


def esc(text: str) -> str:
    """Neutraliza pipes para nao quebrar tabelas Markdown."""
    return text.replace("|", "\\|")


def frontmatter(**kw) -> str:
    lines = ["---"]
    for k, v in kw.items():
        if isinstance(v, list):
            lines.append(f"{k}: [{', '.join(v)}]")
        elif isinstance(v, str) and len(v) >= 2 and v[0] == v[-1] == '"':
            lines.append(f"{k}: {v}")  # ja vem entre aspas (summary, title)
        elif isinstance(v, str) and (":" in v or v.startswith(("<", ">", "["))):
            q = v.replace('"', '\\"')
            lines.append(f'{k}: "{q}"')
        else:
            lines.append(f"{k}: {v}")
    lines.append("---")
    return "\n".join(lines)


